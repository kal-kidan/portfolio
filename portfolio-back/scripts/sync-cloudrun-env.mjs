import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] || path.join(root, 'src/env/env.production');
const target = path.join(root, 'cloudrun.env.yaml');

const SKIP_KEYS = new Set(['PORT', 'DB_TYPE']);

if (!fs.existsSync(source)) {
  console.error(`Env source not found: ${source}`);
  process.exit(1);
}

const vars = { NODE_ENV: 'production' };

for (const line of fs.readFileSync(source, 'utf8').split(/\r?\n/)) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;

  const eq = trimmed.indexOf('=');
  if (eq === -1) continue;

  const key = trimmed.slice(0, eq).trim();
  let value = trimmed.slice(eq + 1).trim();
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    value = value.slice(1, -1);
  }

  if (SKIP_KEYS.has(key)) continue;
  vars[key] = value;
}

const yaml = [
  '# Generated by scripts/sync-cloudrun-env.mjs — do not commit',
  ...Object.entries(vars).map(
    ([key, value]) => `${key}: ${JSON.stringify(value)}`,
  ),
  '',
].join('\n');

fs.writeFileSync(target, yaml);
console.log(`Wrote ${target} (${Object.keys(vars).length} variables)`);
